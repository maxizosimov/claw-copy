import Foundation

/// Recent clipboard texts, newest first. Kept in memory only: never written to disk, and gone
/// when the app quits.
public struct ClipboardHistory: Sendable {
    public static let defaultCapacity = 25

    public private(set) var entries: [String] = []
    public let capacity: Int

    public init(capacity: Int = ClipboardHistory.defaultCapacity) {
        self.capacity = max(1, capacity)
    }

    /// Adds `text` as the newest entry. A text that is already in the history moves to the top
    /// instead of appearing twice. Returns whether the history changed.
    @discardableResult
    public mutating func record(_ text: String) -> Bool {
        if entries.first == text { return false }
        entries.removeAll { $0 == text }
        entries.insert(text, at: 0)
        if entries.count > capacity {
            entries.removeLast(entries.count - capacity)
        }
        return true
    }

    public mutating func clear() {
        entries.removeAll()
    }
}

/// Decides whether a clipboard change may be recorded in the history.
public enum ClipboardRecordPolicy {
    /// Pasteboard types that password managers use to mark secrets.
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    /// Pasteboard types that mark short-lived, auto-generated clipboard contents that no
    /// clipboard history should keep (e.g. text expanders pasting a snippet).
    public static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Secret or short-lived contents: never recorded in the normal history, and never read
    /// unless the user opted in to keeping passwords briefly.
    public static let privateTypes = concealedTypes.union(transientTypes)

    public enum Kind: Equatable, Sendable {
        /// Ordinary text: goes into the normal history.
        case ordinary
        /// A secret (concealed, or copied in a password manager): only the opt-in password list.
        case secret
        /// Never recorded anywhere.
        case ignore
    }

    /// Classifies a clipboard change from its types and source app alone, before its contents
    /// are read, so secrets are only read when they will actually be kept.
    public static func kind(
        pasteboardTypes: [String],
        sourceBundleID: String?,
        copyPolicy: CopyPolicy = CopyPolicy()
    ) -> Kind {
        if pasteboardTypes.contains(where: transientTypes.contains) { return .ignore }
        if pasteboardTypes.contains(where: concealedTypes.contains) { return .secret }
        if copyPolicy.isExcluded(bundleID: sourceBundleID) { return .secret }
        return .ordinary
    }

    /// Whether the text itself is worth keeping (not empty, not oversized).
    public static func isRecordable(_ text: String?, copyPolicy: CopyPolicy = CopyPolicy()) -> Bool {
        guard let text, !text.allSatisfy(\.isWhitespace) else { return false }
        return text.utf16.count <= copyPolicy.maxLength
    }

    public static func shouldRecord(
        text: String?,
        pasteboardTypes: [String],
        sourceBundleID: String?,
        copyPolicy: CopyPolicy = CopyPolicy()
    ) -> Bool {
        kind(pasteboardTypes: pasteboardTypes, sourceBundleID: sourceBundleID, copyPolicy: copyPolicy) == .ordinary
            && isRecordable(text, copyPolicy: copyPolicy)
    }
}

/// Turns an arbitrary clipboard text into a safe, single-line menu title.
public enum HistoryMenuTitle {
    /// Invisible formatting characters that can make text display differently from what it is
    /// (bidirectional overrides, zero-width characters). Stripped from titles.
    static let invisibleRanges: [ClosedRange<UInt32>] = [
        0x00AD...0x00AD, 0x200B...0x200F, 0x202A...0x202E, 0x2060...0x2064, 0x2066...0x2069, 0xFEFF...0xFEFF,
    ]

    /// Shown when a text consists only of invisible characters.
    public static let invisiblePlaceholder = "(invisible characters)"

    public static func make(_ text: String, maxLength: Int = 60) -> String {
        var scalars = String.UnicodeScalarView()
        var scalarCount = 0
        var cutShort = false
        var lastWasSpace = true // also trims leading whitespace
        for scalar in text.unicodeScalars {
            // Enough for any title: stop instead of scanning a (possibly huge) entry to the end.
            if scalarCount > maxLength * 4 {
                cutShort = true
                break
            }
            if invisibleRanges.contains(where: { $0.contains(scalar.value) }) { continue }
            let isSpace = scalar.properties.isWhitespace
                || scalar.properties.generalCategory == .control
                || scalar.properties.generalCategory == .lineSeparator
                || scalar.properties.generalCategory == .paragraphSeparator
            if isSpace {
                if !lastWasSpace {
                    scalars.append(" ")
                    scalarCount += 1
                }
                lastWasSpace = true
            } else {
                scalars.append(scalar)
                scalarCount += 1
                lastWasSpace = false
            }
        }
        var title = String(scalars)
        while title.hasSuffix(" ") { title.removeLast() }
        if title.isEmpty { return invisiblePlaceholder }
        if title.count > maxLength || cutShort {
            title = String(title.prefix(max(1, maxLength - 1))) + "…"
        }
        return title
    }
}

/// A multi-line preview of a clipboard text for the history menu's hover tooltip.
public enum HistoryPreview {
    public static func make(_ text: String, maxLines: Int = 20, maxCharacters: Int = 1000) -> String {
        // Only the start of a (possibly huge) entry can be shown, so only that is processed.
        let head = text.prefix(maxCharacters + 1)
        let headIsWholeText = head.endIndex == text.endIndex

        // Keep line breaks, drop invisible formatting characters and other control characters.
        var scalars = String.UnicodeScalarView()
        var previousWasCR = false
        for scalar in head.unicodeScalars {
            defer { previousWasCR = scalar == "\r" }
            if HistoryMenuTitle.invisibleRanges.contains(where: { $0.contains(scalar.value) }) { continue }
            switch scalar {
            case "\n":
                if !previousWasCR { scalars.append("\n") }
            case "\r", "\u{2028}", "\u{2029}":
                scalars.append("\n")
            case "\t":
                scalars.append(contentsOf: "    ".unicodeScalars)
            default:
                if scalar.properties.generalCategory == .control { continue }
                scalars.append(scalar)
            }
        }
        let cleaned = String(scalars).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleaned.isEmpty else { return HistoryMenuTitle.invisiblePlaceholder }

        let lines = cleaned.split(separator: "\n", omittingEmptySubsequences: false)
        var preview = lines.prefix(max(1, maxLines)).joined(separator: "\n")
        var truncated = lines.count > maxLines || !headIsWholeText
        if preview.count > maxCharacters {
            preview = String(preview.prefix(max(1, maxCharacters)))
            truncated = true
        }
        guard truncated else { return preview }
        let total = text.count.formatted(.number)
        return preview + "\n…\n(\(total) characters in total)"
    }
}
